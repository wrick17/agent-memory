#!/usr/bin/env node
// Self-host setup (docs/self-host.md): checks one settings file, plans the Worker config and the Cloudflare resources the
// Worker binds, and with --apply creates only what is missing, in the account the Wrangler login is verified to reach.
// It never deletes, never overwrites a config, resource or secret, and never deploys. Node 24, no dependencies.
import { spawnSync } from "node:child_process";
import { randomUUID } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import readline from "node:readline";
import { Writable } from "node:stream";
import { fileURLToPath } from "node:url";
import { stripVTControlCharacters } from "node:util";

export const SETTINGS_FILE = "agent-memory.setup.json";
export const CONFIG_FILE = "wrangler.jsonc";
export const RECEIPTS_FILE = "agent-memory.setup-receipts.json";
/** The compatibility date and flags of the checked source (wrangler.jsonc). */
const COMPATIBILITY_DATE = "2026-10-20";
/** Output size of EMBED_MODEL in src/profile/index.ts (@cf/qwen/qwen3-embedding-0.6b). */
const DIMENSIONS = 1024;
/** PROFILES in src/domain/types.ts, without `me`, which routing never targets. */
export const ROUTABLE = ["work", "personal", "test"];
const KEYS = ["account_id", "worker", "public_url", "clerk_issuer", "clerk_publishable_key", "routing", "embeddings", "corpus"];
const OWNER_ID = /^user_[A-Za-z0-9]{8,64}$/;
const RESERVED_HOST = /(^|\.)(example\.(com|net|org)|localhost|local|test|invalid|internal)$/;
const HEADER = `// Generated by \`npm run setup\` (local/setup.mjs, docs/self-host.md). Setup never overwrites this file.
// OWNER_USER_ID is a Worker secret, not a variable. BACKUPS is the permanent R2 generation ledger, not a backup.
`;

export const names = (worker) => ({ ledger: `${worker}-ledger`, index: `${worker}-cards` });

/** Exactly an https origin on a public DNS name: no path, port, credentials, query or trailing slash. */
function httpsOrigin(value, what, errors) {
	let u = null;
	try { u = new URL(value); } catch { /* reported below */ }
	if (!u || u.protocol !== "https:" || u.port || u.origin !== value) {
		errors.push(`${what} must be an https origin with no path, port or trailing slash, like https://memory.<your domain>`);
		return null;
	}
	if (!/^[a-z0-9-]+(\.[a-z0-9-]+)+$/.test(u.hostname) || /^[\d.]+$/.test(u.hostname) || RESERVED_HOST.test(u.hostname)) {
		errors.push(`${what} host ${u.hostname} is not a public DNS name you can own`);
		return null;
	}
	return u;
}

/** A Clerk publishable key is pk_live_ or pk_test_ plus base64 of "<Frontend API host>$". */
function clerkFrontend(key, errors) {
	const m = /^pk_(?:live|test)_([A-Za-z0-9+/=_-]+)$/.exec(typeof key === "string" ? key : "");
	const host = m ? Buffer.from(m[1], "base64").toString("utf8") : "";
	if (!host.endsWith("$")) {
		errors.push("clerk_publishable_key must be the pk_live_… or pk_test_… publishable key from the Clerk dashboard");
		return null;
	}
	return httpsOrigin(`https://${host.slice(0, -1)}`, "the Clerk Frontend API named by clerk_publishable_key", errors);
}

/** Whether this source has the corpus class wired in. Until it does, the corpus cannot be turned on. */
export const corpusIntegrated = (workerSource) => /export\s*\{[^}]*\bCorpusStore\b[^}]*\}|export\s+class\s+CorpusStore\b/.test(workerSource);

/** Every problem with the settings, or the values the config needs. Pure: no files, no network. */
export function check(s, workerSource) {
	const errors = [];
	if (!s || typeof s !== "object" || Array.isArray(s)) return { errors: ["the settings file must hold one JSON object"] };
	for (const k of Object.keys(s)) if (!KEYS.includes(k)) errors.push(`unknown setting ${k}`);
	for (const k of KEYS) if (s[k] === undefined) errors.push(`missing setting ${k}`);
	if (s.account_id !== undefined && !/^[0-9a-f]{32}$/.test(s.account_id)) errors.push("account_id must be the 32-character Cloudflare account id");
	if (s.worker !== undefined && !/^[a-z][a-z0-9-]{0,24}[a-z0-9]$/.test(s.worker)) {
		errors.push("worker must be 2 to 26 lowercase letters, digits or dashes, starting with a letter; it also names the R2 bucket and Vectorize index");
	}
	const site = s.public_url === undefined ? null : httpsOrigin(s.public_url, "public_url", errors);
	// A workers.dev origin is only ever the Worker's own URL, <worker>.<account subdomain>.workers.dev. Setup compares the
	// subdomain with the account's before planning, so a matching suffix alone never names someone else's Worker as ours.
	const labels = site ? site.hostname.split(".") : [];
	const workersDev = /(^|\.)workers\.dev$/.test(site?.hostname ?? "");
	if (workersDev && (labels.length !== 4 || labels[0] !== s.worker)) {
		errors.push(`a workers.dev public_url must be this Worker's own URL, https://${s.worker}.<your account's workers.dev subdomain>.workers.dev`);
	}
	const frontend = s.clerk_publishable_key === undefined ? null : clerkFrontend(s.clerk_publishable_key, errors);
	if (s.clerk_issuer !== undefined && httpsOrigin(s.clerk_issuer, "clerk_issuer", errors) && frontend && s.clerk_issuer !== frontend.origin) {
		errors.push(`clerk_issuer must equal the Clerk Frontend API ${frontend.origin} named by clerk_publishable_key; Clerk signs tokens with that issuer`);
	}
	if (site && frontend && site.hostname === frontend.hostname) errors.push("public_url and the Clerk Frontend API must be different hosts");
	if (s.routing !== undefined && !Array.isArray(s.routing)) errors.push("routing must be a list of \"pattern=profile\" strings");
	for (const rule of Array.isArray(s.routing) ? s.routing : []) {
		const at = typeof rule === "string" ? rule.lastIndexOf("=") : -1;
		const pattern = at > 0 ? rule.slice(0, at) : "", profile = at > 0 ? rule.slice(at + 1) : "";
		if (!pattern || /[\s,]/.test(pattern) || !ROUTABLE.includes(profile) || (pattern.startsWith("path:") && !pattern.startsWith("path:/"))) {
			errors.push(`routing rule ${JSON.stringify(rule)} must be "host/owner/repo-glob=profile" or "path:/absolute/dir=profile", with profile ${ROUTABLE.join(", ")}`);
		}
	}
	for (const k of ["embeddings", "corpus"]) if (s[k] !== undefined && s[k] !== "on" && s[k] !== "off") errors.push(`${k} must be "on" or "off"`);
	const integrated = corpusIntegrated(workerSource);
	if (s.corpus === "on" && !integrated) errors.push("corpus \"on\" needs the CorpusStore class exported from src/worker.ts, which this source does not have yet; set corpus to \"off\"");
	return errors.length ? { errors } : { errors, values: { frontend: frontend.origin, host: site.hostname, integrated, workersDev: workersDev ? labels[1] : null } };
}

/** The Worker config for these settings: the exact bindings and variables the source reads, nothing else. */
export function render(s, { frontend, host, integrated, workersDev }) {
	const { ledger, index } = names(s.worker);
	const corpus = s.corpus === "on";
	const embeddings = s.embeddings === "on";
	const config = {
		$schema: "node_modules/wrangler/config-schema.json",
		name: s.worker,
		account_id: s.account_id,
		main: "src/worker.ts",
		compatibility_date: COMPATIBILITY_DATE,
		// global_fetch_strictly_public: the Worker fetches Clerk's signing keys from the public Frontend API, even when that
		// host is a CNAME in the Worker's own zone.
		compatibility_flags: ["nodejs_compat", "global_fetch_strictly_public"],
		// workers.dev needs no route or DNS record. Version preview URLs would be more public origins than RESOURCE_URL names.
		...(workersDev ? { workers_dev: true, preview_urls: false } : { routes: [{ pattern: host, custom_domain: true }] }),
		observability: { enabled: true },
		// The viewer snapshot (src/v2-api.ts) reads the deployed version id and time from this binding.
		version_metadata: { binding: "CF_VERSION_METADATA" },
		durable_objects: { bindings: [
			{ name: "ACCOUNT", class_name: "AccountStore" },
			{ name: "PROFILE", class_name: "ProfileStore" },
			...(corpus ? [{ name: "CORPUS_STORE", class_name: "CorpusStore" }] : []),
		] },
		migrations: [
			{ tag: "v1", new_sqlite_classes: ["AccountStore", "ProfileStore"] },
			...(corpus ? [{ tag: "v2", new_sqlite_classes: ["CorpusStore"] }] : []),
		],
		r2_buckets: [{ binding: "BACKUPS", bucket_name: ledger }],
		...(embeddings ? { ai: { binding: "AI" }, vectorize: [{ binding: "VECTORS", index_name: index }] } : {}),
		vars: {
			RESOURCE_URL: `${s.public_url}/mcp`,
			CLERK_ISSUER: s.clerk_issuer,
			CLERK_FRONTEND_API: frontend,
			CLERK_PUBLISHABLE_KEY: s.clerk_publishable_key,
			REQUIRED_SCOPE: "memory",
			DASHBOARD_ORIGIN: s.public_url,
			EMBEDDINGS: s.embeddings,
			ROUTING_DEFAULTS: s.routing.join(","),
			IMPORT_PROFILES: "",
			...(integrated ? { CORPUS: s.corpus } : {}),
		},
	};
	return `${HEADER}${JSON.stringify(config, null, "\t")}\n`;
}

/** The config file Wrangler would use from `root`: it searches each name up the tree, wrangler.json first. */
export function discoveredConfig(root) {
	for (const name of ["wrangler.json", "wrangler.jsonc", "wrangler.toml"]) {
		for (let dir = root; ; dir = path.dirname(dir)) {
			if (fs.existsSync(path.join(dir, name))) return path.join(dir, name);
			if (path.dirname(dir) === dir) break;
		}
	}
	return null;
}

/** Wrangler from this checkout, non-interactive (stdin is a pipe), pinned to the settings' account, without telemetry. */
function wranglerCli(root, accountId) {
	const bin = path.join(root, "node_modules", "wrangler", "bin", "wrangler.js");
	return (args, input = "") => {
		if (!fs.existsSync(bin)) return { status: 1, stdout: "", stderr: "Wrangler is not installed in this checkout; run npm ci first" };
		const r = spawnSync(process.execPath, [bin, ...args], { cwd: root, input, encoding: "utf8", maxBuffer: 16 * 1024 * 1024,
			env: { ...process.env, CLOUDFLARE_ACCOUNT_ID: accountId, WRANGLER_SEND_METRICS: "false", WRANGLER_HIDE_BANNER: "true" } });
		return { status: r.status ?? 1, stdout: r.stdout ?? "", stderr: r.stderr || r.error?.message || "" };
	};
}

async function askOwnerId() {
	if (!process.stdin.isTTY) throw new Refusal("enter the owner id in an interactive terminal; nothing was changed");
	const wasRaw = !!process.stdin.isRaw;
	const muted = new Writable({ write(_chunk, _encoding, done) { done(); } });
	const rl = readline.createInterface({ input: process.stdin, output: muted, terminal: true });
	try {
		return await new Promise((resolve, reject) => {
			const cancel = () => reject(new Refusal("no owner id was entered; nothing was changed"));
			rl.once("line", (line) => resolve(line.trim()));
			rl.once("SIGINT", cancel);
			rl.once("close", cancel);
			// Readline enables raw mode before the prompt, and its output never reaches either terminal stream.
			process.stderr.write("Clerk user id of the owner (user_…), hidden, sent only to Wrangler: ");
		});
	} finally {
		rl.close();
		process.stdin.setRawMode(wasRaw);
		muted.destroy();
		process.stderr.write("\n");
	}
}

class Refusal extends Error {}

/** A config is public output, never proof that setup created a remote resource. */
function creationReceipts(root, accountId) {
	const file = path.join(root, RECEIPTS_FILE);
	let resources = {};
	try {
		const saved = JSON.parse(fs.readFileSync(file, "utf8"));
		if (saved?.version !== 1 || !saved.resources || typeof saved.resources !== "object" || Array.isArray(saved.resources) ||
			Object.values(saved.resources).some((v) => v !== "pending" && v !== "created")) throw new Error("invalid receipts");
		resources = saved.resources;
	} catch (e) {
		if (e.code !== "ENOENT") throw new Refusal(`${RECEIPTS_FILE} cannot be read as valid creation receipts; nothing was changed`);
	}
	return {
		key: (kind, name) => `${accountId}/${kind}/${name}`,
		status: (key) => resources[key],
		record(key, status) {
			resources[key] = status;
			const temp = `${file}.${randomUUID()}.tmp`;
			let fd;
			try {
				fd = fs.openSync(temp, "wx", 0o600);
				fs.writeFileSync(fd, `${JSON.stringify({ version: 1, resources }, null, "\t")}\n`);
				fs.fsyncSync(fd);
				fs.closeSync(fd); fd = undefined;
				fs.renameSync(temp, file);
				fd = fs.openSync(root, "r");
				fs.fsyncSync(fd);
			} catch {
				throw new Refusal(`cannot durably record creation in ${RECEIPTS_FILE}; setup stopped. Keep the receipts and inspect the account before retrying.`);
			} finally {
				if (fd !== undefined) fs.closeSync(fd);
				fs.rmSync(temp, { force: true });
			}
		},
	};
}

const tail = (r) => stripVTControlCharacters(`${r.stderr}\n${r.stdout}`).trim().split("\n").slice(-6).join("\n");

/**
 * The account's workers.dev subdomain, or null when it has none: one GET with the Wrangler login's own token, which
 * `wrangler auth token --json` refreshes when expired. The token is never printed, saved or put on a command line.
 */
async function workersSubdomain(run, accountId, request) {
	const auth = run(["auth", "token", "--json"]);
	let token = null;
	try { const t = JSON.parse(auth.stdout); if (t.type === "oauth" || t.type === "api_token") token = t.token; } catch { /* refused below */ }
	if (auth.status !== 0 || typeof token !== "string" || !token) {
		throw new Refusal("cannot read the Wrangler login's token to check the account's workers.dev subdomain. Use `npx wrangler login` or " +
			"CLOUDFLARE_API_TOKEN; nothing was changed");
	}
	let res = null, body = null;
	try {
		res = await request(`https://api.cloudflare.com/client/v4/accounts/${accountId}/workers/subdomain`,
			{ headers: { Authorization: `Bearer ${token}` }, redirect: "error" });
		body = await res.json();
	} catch { /* refused below */ }
	// 10007 is Cloudflare's "no workers.dev subdomain" error, which Wrangler's own deploy handles the same way.
	if (Array.isArray(body?.errors) && body.errors.some((e) => e?.code === 10007)) return null;
	if (!res?.ok || body?.success !== true || typeof body.result?.subdomain !== "string") {
		throw new Refusal(`reading the workers.dev subdomain of account ${accountId} failed${res ? ` (HTTP ${res.status})` : ""}; nothing was changed`);
	}
	return body.result.subdomain;
}

/**
 * Plans, and with --apply, provisions. Returns the exit code: 0 done or planned, 1 refused or failed, 2 usage.
 * `wrangler(args, stdin)`, `fetch` and `readOwnerId()` are injectable for tests; the owner id goes only to `secret put` on stdin.
 */
export async function setup({ root, argv = [], wrangler, fetch: request = globalThis.fetch, readOwnerId = askOwnerId, log = console.log } = {}) {
	if (argv.length === 1 && ["--help", "-h"].includes(argv[0])) {
		log("usage: npm run setup [-- [settings.json] [--apply]]   (default settings file: agent-memory.setup.json)\n" +
			"Plan reads your Cloudflare account. --apply creates the planned resources. See docs/self-host.md.");
		return 0;
	}
	const apply = argv.includes("--apply");
	const rest = argv.filter((a) => a !== "--apply");
	if (rest.length > 1 || rest.some((a) => a.startsWith("-"))) {
		log("usage: npm run setup [-- [settings.json] [--apply]]   (default settings file: agent-memory.setup.json)");
		return 2;
	}
	let lockFd, lockStat, lockPath;
	try {
		if (apply) {
			lockPath = path.join(root, "agent-memory.setup.lock");
			try { lockFd = fs.openSync(lockPath, "wx", 0o600); } catch (e) {
				if (e.code !== "EEXIST") throw e;
				throw new Refusal("another setup apply holds agent-memory.setup.lock; nothing was inspected or changed. " +
					"After an interrupted apply, verify no setup process is running before removing its lock yourself.");
			}
			lockStat = fs.fstatSync(lockFd);
			fs.writeFileSync(lockFd, JSON.stringify({ pid: process.pid, at: new Date().toISOString() }));
			fs.fsyncSync(lockFd);
		}
		const file = rest[0] ? path.resolve(rest[0]) : path.join(root, SETTINGS_FILE);
		let settings;
		try { settings = JSON.parse(fs.readFileSync(file, "utf8")); } catch (e) {
			throw new Refusal(`cannot read settings ${file}: ${e.code === "ENOENT" ? "no such file (see docs/self-host.md#write-the-settings)" : "not valid JSON"}`);
		}
		let source;
		try { source = fs.readFileSync(path.join(root, "src", "worker.ts"), "utf8"); } catch {
			throw new Refusal(`${root} is not the Agent Memory source directory (no src/worker.ts)`);
		}
		const { errors, values } = check(settings, source);
		if (errors.length) throw new Refusal(`the settings in ${file} are not usable:\n  - ${errors.join("\n  - ")}`);
		const s = settings, target = path.join(root, CONFIG_FILE), text = render(s, values), { ledger, index } = names(s.worker);
		const found = discoveredConfig(root);
		if (found && (found !== target || fs.readFileSync(found, "utf8") !== text)) {
			throw new Refusal(`${found} exists and is not the config this setup generates from ${file}. Setup never overwrites or edits a ` +
				"Wrangler config. Move it out of the way (it may belong to another deployment), or restore the file this setup wrote earlier.");
		}
		const receipts = creationReceipts(root, s.account_id);
		const bucketKey = receipts.key("r2", ledger), indexKey = receipts.key("vectorize", index), workerKey = receipts.key("worker", s.worker);
		const run = wrangler ?? wranglerCli(root, s.account_id);
		const read = (args, r = run(args)) => {
			if (r.status !== 0) throw new Refusal(`wrangler ${args.join(" ")} failed, nothing was changed:\n${tail(r)}`);
			return r.stdout;
		};
		const readJson = (args, r) => {
			const out = read(args, r);
			try { return JSON.parse(out); } catch { throw new Refusal(`wrangler ${args.join(" ")} printed something other than JSON; nothing was changed`); }
		};

		// The login and its account, before anything else touches Cloudflare. The email in this output is never printed.
		const who = run(["whoami", "--json"]);
		let me = null;
		try { me = JSON.parse(who.stdout); } catch { /* not logged in */ }
		if (who.status !== 0 || !me?.loggedIn) {
			throw new Refusal("Wrangler has no Cloudflare login. Run `npx wrangler login` yourself (or set CLOUDFLARE_API_TOKEN to a token " +
				"for this account), then rerun. Setup does not log in or ask for broader access.");
		}
		if (!(me.accounts ?? []).some((a) => a.id === s.account_id)) {
			throw new Refusal(`account_id ${s.account_id} is not an account this Cloudflare login can use (it can use: ${(me.accounts ?? []).map((a) => a.id).join(", ") || "none"}).`);
		}
		// A workers.dev URL is ours only on this account's own subdomain. Setup reads it and never registers or changes it.
		if (values.workersDev) {
			const actual = await workersSubdomain(run, s.account_id, request);
			if (actual !== values.workersDev) {
				throw new Refusal(actual === null
					? `account ${s.account_id} has no workers.dev subdomain. Register one in the Cloudflare dashboard yourself, then set public_url to ` +
						`https://${s.worker}.<that subdomain>.workers.dev; nothing was changed`
					: `public_url ${s.public_url} is not on this account's workers.dev subdomain ${actual}.workers.dev. Use ` +
						`https://${s.worker}.${actual}.workers.dev or your own domain; nothing was changed`);
			}
		}

		// Read-only inspection of the names this config binds.
		const buckets = [...stripVTControlCharacters(read(["r2", "bucket", "list"])).matchAll(/^name:\s+(\S+)\s*$/gm)].map((m) => m[1]);
		const indexes = s.embeddings === "on" ? readJson(["vectorize", "list", "--json"]) : [];
		const vector = indexes.find((i) => i.name === index);
		const metadata = vector ? readJson(["vectorize", "list-metadata-index", index, "--json"]) : [];
		const secretList = ["secret", "list", "--name", s.worker, "--format", "json"];
		const listed = run(secretList);
		// Wrangler reports an absent Worker as an error naming it; any other failure stops setup. Search all of its output:
		// the error's notes and Wrangler's default log-file footer push the naming line out of the displayed tail.
		const absent = listed.status !== 0 && stripVTControlCharacters(`${listed.stderr}\n${listed.stdout}`).includes(`Worker "${s.worker}" not found`);
		const secrets = absent ? null : readJson(secretList, listed).map((x) => x.name);

		// Pending intent survives a failed create or a crash before the success receipt. Neither proves ownership.
		const steps = [];
		const step = (what, present, exact, cmd, input, key) => steps.push(!present ? { what, status: "create", cmd, input, key }
			: key && receipts.status(key) !== "created" ? { what, status: "refuse", why: receipts.status(key) === "pending"
				? "an earlier run started creating it but did not confirm it; setup cannot prove it created it (inspect the account or choose another worker name)"
				: "already exists in this account, and setup has no receipt of creating it (choose another worker name)" }
				: exact === true ? { what, status: "keep" } : { what, status: "refuse", why: exact });
		steps.push(!found ? { what: `${CONFIG_FILE} (Worker config, no secrets)`, status: "create" } : { what: `${CONFIG_FILE}`, status: "keep" });
		step(`R2 bucket ${ledger} (BACKUPS binding: the permanent generation ledger)`, buckets.includes(ledger), true, ["r2", "bucket", "create", ledger], undefined, bucketKey);
		if (s.embeddings === "on") {
			step(`Vectorize index ${index}: ${DIMENSIONS} dimensions, cosine`, !!vector,
				vector?.config?.dimensions === DIMENSIONS && vector?.config?.metric === "cosine" ||
					`has ${vector?.config?.dimensions} dimensions and metric ${vector?.config?.metric}; this source needs ${DIMENSIONS}, cosine`,
				["vectorize", "create", index, "--dimensions", String(DIMENSIONS), "--metric", "cosine"], undefined, indexKey);
			const kind = metadata.find((m) => m.propertyName === "kind");
			step(`string metadata index on kind for ${index}`, !!kind, String(kind?.indexType).toLowerCase() === "string" || `has type ${kind?.indexType}`,
				["vectorize", "create-metadata-index", index, "--propertyName", "kind", "--type", "string"]);
		}
		const worker = secrets !== null, ownerSet = !!secrets?.includes("OWNER_USER_ID");
		step(`Worker ${s.worker}${worker ? "" : " (Wrangler creates it as an empty draft with the secret below; `wrangler deploy` uploads the code)"}`, worker, true, undefined, undefined, workerKey);
		step(`Worker secret OWNER_USER_ID (${ownerSet ? "setup never changes it" : "your Clerk user id, read from your input and sent to Wrangler on stdin"})`,
			ownerSet, true, ["secret", "put", "OWNER_USER_ID", "--name", s.worker], "owner", worker ? undefined : workerKey);

		log(`Agent Memory setup for Cloudflare account ${s.account_id}, Worker ${s.worker}, ${s.public_url}`);
		for (const x of steps) log(`  ${x.status.padEnd(6)} ${x.what}${x.why ? `: ${x.why}` : ""}`);
		if (values.workersDev) log("  on     workers.dev: deploy serves the Worker at this URL with preview URLs off; no custom domain, route or DNS record");
		if (s.embeddings === "off") log("  off    embeddings: no Workers AI or Vectorize binding; recall is lexical");
		log(s.corpus === "on" ? "  on     corpus: CorpusStore under CORPUS_STORE, migration v2 (Workers Paid only)" : "  off    corpus");
		log("  never  deletes, overwrites, deploys, changes Clerk or DNS, installs capture, or creates backup keys (see docs/self-host.md)");
		const refused = steps.filter((x) => x.status === "refuse");
		if (refused.length) throw new Refusal("planned names collide with existing resources (the refuse lines above); nothing was changed.");
		if (!apply) {
			log(`Plan only; nothing was changed. Rerun with --apply to make these changes in account ${s.account_id}.`);
			return 0;
		}

		const todo = steps.filter((x) => x.status === "create" && x.cmd);
		let owner = "";
		if (todo.some((x) => x.input === "owner")) {
			owner = await readOwnerId();
			if (!OWNER_ID.test(owner)) throw new Refusal("that is not a Clerk user id (user_ followed by letters and digits); nothing was changed");
		}
		// "wx" fails if the file appeared since the check: still no overwrite.
		if (!found) fs.writeFileSync(target, text, { flag: "wx" });
		for (const x of todo) {
			if (x.key) receipts.record(x.key, "pending");
			const r = run(x.cmd, x.input === "owner" ? owner : "");
			if (r.status !== 0) {
				throw new Refusal(`creating ${x.what} failed:\n${tail(r).replaceAll(owner || "\0", "[owner id]")}\n` +
					"Everything created so far stays. Fix the cause and rerun `npm run setup -- --apply` to resume.");
			}
			if (x.key) receipts.record(x.key, "created");
			log(`  done   ${x.what}`);
		}
		log("Setup is complete. Next: run `npx wrangler deploy` in an interactive terminal (docs/self-host.md#deploy).");
		return 0;
	} catch (e) {
		if (!(e instanceof Refusal)) throw e;
		log(`setup refused: ${e.message}`);
		return 1;
	} finally {
		if (lockFd !== undefined) {
			try {
				let current;
				try { current = fs.lstatSync(lockPath); } catch (e) { if (e.code !== "ENOENT") throw e; }
				// Keep the descriptor open while checking identity, so a replaced lock cannot reuse its inode.
				if (current && current.dev === lockStat?.dev && current.ino === lockStat?.ino) fs.unlinkSync(lockPath);
			} finally { fs.closeSync(lockFd); }
		}
	}
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
	setup({ root: path.resolve(path.dirname(fileURLToPath(import.meta.url)), ".."), argv: process.argv.slice(2) })
		.then((code) => process.exit(code), (e) => { console.error(e); process.exit(1); });
}
